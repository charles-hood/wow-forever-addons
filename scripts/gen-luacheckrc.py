#!/usr/bin/env python3
"""Write .luacheckrc with read_globals taken from the client's own API dump.

Usage: gen-luacheckrc.py types/api.json .luacheckrc
"""
import json
import sys

# Lua-side globals the C API dump does not list (FrameXML constants, Lua libs, our own).
EXTRA_READ = """
date time strsplit strtrim strjoin tinsert tremove wipe format unpack
Enum NUM_BAG_SLOTS INVSLOT_AMMO INVSLOT_RANGED INVSLOT_MAINHAND INVSLOT_OFFHAND
WOW_PROJECT_ID WOW_PROJECT_MAINLINE WOW_PROJECT_CLASSIC LE_EXPANSION_LEVEL_CURRENT
UIParent GameTooltip Minimap PixelUtil loadstring_untainted GetClassicExpansionLevel
IsMacClient GetLocale GetRealmName ReloadUI CreateMacro UnitPowerType
GameFontNormal GameFontNormalLarge GameFontHighlight
""".split()

OUR_GLOBALS = """
ForeverProbeDB ForeverProbeCharDB HunterProbeDB HunterHUDDB ForeverProbe SlashCmdList
SLASH_FOREVERPROBE1 SLASH_FOREVERPROBE2 SLASH_HUNTERPROBE1 SLASH_HUNTERPROBE2 SLASH_HUNTERHUD1 SLASH_HUNTERHUD2
""".split()


def main(src, dst):
    with open(src) as f:
        api = json.load(f)
    names = set(api.get("globals", {}).keys())
    for s in api.get("systems", []):
        ns = s.get("namespace")
        if ns:
            names.add(ns)
    names.update(EXTRA_READ)
    names = sorted(n for n in names if n.replace("_", "a").isalnum())
    with open(dst, "w") as f:
        f.write("-- generated by scripts/gen-luacheckrc.py from the client API dump; do not edit\n")
        f.write('std = "lua51"\n')
        f.write("max_line_length = false\n")
        f.write("unused_args = false\n")
        f.write("ignore = { \"212\", \"213\" }\n")
        f.write("globals = {\n")
        for n in OUR_GLOBALS:
            f.write(f'  "{n}",\n')
        f.write("}\n")
        f.write("read_globals = {\n")
        for n in names:
            f.write(f'  "{n}",\n')
        f.write("}\n")
    print(f"wrote {dst} with {len(names)} read_globals")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
